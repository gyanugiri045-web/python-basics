class Employee:
    language="py"       #This is class attrubute
    salary=120000

reyan=Employee()
reyan.name="reyan"     #This is an object attribute
print(reyan.name,reyan.language,reyan.salary)

ram=Employee()
ram.name="ram"
print(ram.name,ram.language,ram.salary)

# here name is object attribute and salary and language are class attribute  they directly belong to class